package Lista2;
public class Ex8 {
	public static void main(String[] args) {
	    
		double temperatura = 26.78;
		int tempInteira;
		double tempDouble;

		tempInteira = (int) temperatura;
		tempDouble = (double) tempInteira;
		System.out.println("Temperatura original: " + temperatura);
		System.out.println("Temperatura inteira: " + tempInteira);
		System.out.println("Temperatura convertida para double: " + tempDouble);
	}

}
